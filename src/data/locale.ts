export const langs = ["de", "en", "fr", "es", "pt", "it", "nl", "pl", "tr", "ja", "ko", "zh"] as const;

export type Lang = (typeof langs)[number];

export type Copy = Record<Lang, string>;

export function L(text: Copy): Copy {
  return text;
}

export function same(text: string): Copy {
  return Object.fromEntries(langs.map((lang) => [lang, text])) as Copy;
}

export function joinName(name: string, text: Copy): Copy {
  return Object.fromEntries(langs.map((lang) => [lang, `${name}. ${text[lang]}`])) as Copy;
}

