/** Short calendar label, without the year. Advent rows use this. */
export function dayNote(month: number, day: number): Copy {
  return Object.fromEntries(
    langs.map((lang) => {
      if (lang === "de") return [lang, `${day}.${String(month).padStart(2, "0")}.`];
      if (lang === "ja" || lang === "zh") return [lang, `${month}月${day}日`];
      if (lang === "ko") return [lang, `${month}월 ${day}일`];
      return [lang, `${day} ${shortMonths[lang][month - 1]}`];
    }),
  ) as Copy;
}

